//

#include <iostream>
#include <string>
#include <vector>

using namespace std;

// Класс "Книга" 
class Book {
private:
    string title;
    string author;
    int year;

    // Статическое поле для подсчета всех созданных книг
    static int totalBooks;

public:
    // Конструктор
    Book(const string& t, const string& a, int y) : title(t), author(a), year(y) {
        totalBooks++; // Увеличение счетчика при создании
        cout << "[Создана книга]: \"" << title << "\" (" << author << ", " << year << ")" << endl;
    }

    // Деструктор
    ~Book() {
        totalBooks--; // Уменьшение счетчика при уничтожении
        cout << "[Удалена книга]: \"" << title << "\"" << endl;
    }

    // Статический метод для получения количества книг
    static int getTotalBooks() {
        return totalBooks;
    }

    // Метод для вывода информации
    void printInfo() const {
        cout << "  - \"" << title << "\", автор: " << author << ", год: " << year << endl;
    }
};

// Инициализация статического поля вне класса
int Book::totalBooks = 0;


// Класс "Библиотека" (Целое)
class Library {
private:
    string name;
    // Агрегация: храним указатели на книги, библиотека не владеет ими
    vector<Book*> books;

public:
    Library(const string& n) : name(n) {
        cout << "[Открыта библиотека]: \"" << name << "\"" << endl;
    }

    // Деструктор библиотеки
    ~Library() {
        cout << "[Закрыта библиотека]: \"" << name << "\"" << endl;
    }

    // Добавление книги в библиотеку
    void addBook(Book* book) {
        if (book != nullptr) { // Проверка на nullptr (требование критериев)
            books.push_back(book);
            cout << "Книга добавлена в фонд библиотеки." << endl;
        }
        else {
            cout << "Ошибка: попытка добавить пустой указатель!" << endl;
        }
    }

    // Вывод всех книг библиотеки
    void printCatalog() const {
        cout << "\n--- Каталог библиотеки \"" << name << "\" ---" << endl;
        if (books.empty()) {
            cout << "  (Библиотека пуста)" << endl;
        }
        else {
            for (const auto* book : books) {
                book->printInfo();
            }
        }
        cout << "-----------------------------------" << endl;
    }
};

int main() {
    setlocale(LC_ALL, "ru");

    cout << "Начало работы программы.\n" << endl;
    cout << "Всего книг в системе: " << Book::getTotalBooks() << "\n" << endl;

    //  Создание книги независимо от библиотеки
    cout << "--- Создание книг ---" << endl;
    Book b1("Война и мир", "Л.Н. Толстой", 1869);
    Book b2("Преступление и наказание", "Ф.М. Достоевский", 1866);
    Book b3("Мастер и Маргарита", "М.А. Булгаков", 1967);

    cout << "\nВсего книг в системе: " << Book::getTotalBooks() << "\n" << endl;

    // Создание библиотеки и добавление в нее книги
    {
        cout << "--- Работа библиотеки ---" << endl;
        Library lib("Городская библиотека №1");

        lib.addBook(&b1);
        lib.addBook(&b2);
        lib.addBook(nullptr); // Демонстрация обработки граничного случая
        lib.addBook(&b3);

        lib.printCatalog();

        cout << "\n[Библиотека выходит из области видимости и будет уничтожена...]" << endl;
    } // Здесь вызывается деструктор Library, но книги b1, b2, b3 остаются 

    // Демонстрация того, что книги остались после закрытия библиотеки
    cout << "\n--- После закрытия библиотеки ---" << endl;
    cout << "Всего книг в системе: " << Book::getTotalBooks() << endl;
    cout << "Книги все еще существуют и доступны:" << endl;
    b1.printInfo();
    b2.printInfo();

    cout << "\n[Конец программы. Объекты b1, b2, b3 будут удалены...]" << endl;
    return 0;
}

